def detect_platform(url: str) -> str:
    """自动检测视频平台"""
    if 'bilibili.com' in url or 'b23.tv' in url:
        return 'bilibili'
    elif 'douyin.com' in url or 'v.douyin.com' in url or 'iesdouyin.com' in url:
        return 'douyin'
    else:
        return 'unknown'


def create_cookie_file(cookie_str: str) -> str:
    """
    从 Cookie 字符串创建临时 Cookie 文件
    
    支持两种格式：
    1. Netscape 格式（多行，制表符分隔）
    2. 普通字符串格式（key=value; key2=value2）
    """
    temp_file = tempfile.NamedTemporaryFile(mode='w', suffix='.txt', delete=False)
    
    # 检查是否已经是 Netscape 格式
    if '\t' in cookie_str and cookie_str.startswith('#') or cookie_str.startswith('.'):
        # Netscape 格式，直接写入
        temp_file.write(cookie_str)
    else:
        # 普通格式，转换为 Netscape 格式
        temp_file.write("# Netscape HTTP Cookie File\n")
        temp_file.write("# Generated by Coze Video API\n\n")
        
        # 解析 Cookie
        cookies = cookie_str.split(';')
        for cookie in cookies:
            cookie = cookie.strip()
            if '=' in cookie:
                key, value = cookie.split('=', 1)
                key = key.strip()
                value = value.strip()
                
                # 根据平台确定域名
                domain = '.bilibili.com'  # 默认
                if 'SESSDATA' in cookie_str:
                    domain = '.bilibili.com'
                elif 'ttwid' in cookie_str or 'sessionid' in cookie_str:
                    domain = '.douyin.com'
                
                # Netscape 格式：domain flag path secure expiry name value
                temp_file.write(f"{domain}\tTRUE\t/\tFALSE\t0\t{key}\t{value}\n")
    
    temp_file.close()
    return temp_file.name


def extract_video_info(url: str, platform: str = "auto", cookie: Optional[str] = None) -> Dict[str, Any]:
    """提取视频信息"""
    import shutil
    
    yt_dlp = get_yt_dlp_path()
    
    # 自动检测平台
    if platform == "auto":
        platform = detect_platform(url)
        logger.info(f"Auto-detected platform: {platform}")
    
    cmd = [
        yt_dlp,
        "--dump-json",
        "--no-download",
    ]
    
    # 处理 Cookie
    if cookie:
        cookie_file = create_cookie_file(cookie)
        cmd.extend(["--cookies", cookie_file])
    
    cmd.append(url)
    
    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=60
        )
        
        # 清理临时 Cookie 文件
        if cookie:
            try:
                os.unlink(cookie_file)
            except:
                pass
        
        if result.returncode != 0:
            logger.error(f"yt-dlp error: {result.stderr}")
            return {"error": result.stderr}
        
        return json.loads(result.stdout)
    except subprocess.TimeoutExpired:
        logger.error("Command timeout")
        return {"error": "Command timeout"}
    except json.JSONDecodeError as e:
        logger.error(f"JSON decode error: {e}")
        return {"error": f"JSON decode error: {str(e)}"}


def download_video(
    url: str,
    output_dir: str,
    quality: str = "best",
    platform: str = "auto",
    cookie: Optional[str] = None
) -> Dict[str, Any]:
    """下载视频"""
    import shutil
    
    yt_dlp = get_yt_dlp_path()
    
    # 自动检测平台
    if platform == "auto":
        platform = detect_platform(url)
    
    # 构建画质参数
    format_map = {
        "best": "bestvideo+bestaudio/best",
        "4k": "bestvideo[height<=2160]+bestaudio/best[height<=2160]",
        "1080p": "bestvideo[height<=1080]+bestaudio/best[height<=1080]",
        "720p": "bestvideo[height<=720]+bestaudio/best[height<=720]",
        "480p": "bestvideo[height<=480]+bestaudio/best[height<=480]",
    }
    
    format_str = format_map.get(quality, format_map["best"])
    
    cmd = [
        yt_dlp,
        "-f", format_str,
        "--merge-output-format", "mp4",
        "--output", os.path.join(output_dir, "%(title)s.%(ext)s"),
        "--no-mtime",
    ]
    
    # 处理 Cookie
    if cookie:
        cookie_file = create_cookie_file(cookie)
        cmd.extend(["--cookies", cookie_file])
    
    cmd.append(url)
    
    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=600  # 10 分钟超时
        )
        
        # 清理临时 Cookie 文件
        if cookie:
            try:
                os.unlink(cookie_file)
            except:
                pass
        
        if result.returncode != 0:
            logger.error(f"Download error: {result.stderr}")
            return {"success": False, "error": result.stderr}
        
        # 查找下载的文件
        files = list(Path(output_dir).glob("*.mp4"))
        if files:
            return {
                "success": True,
                "file_path": str(files[-1]),
                "filename": files[-1].name
            }
        
        return {"success": False, "error": "File not found after download"}
    except subprocess.TimeoutExpired:
        logger.error("Download timeout")
        return {"success": False, "error": "Download timeout"}


