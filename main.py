def convert_cookie_to_netscape(cookie_str: str) -> str:
    """将浏览器 Cookie 字符串转换为 Netscape 格式"""
    lines = ["# Netscape HTTP Cookie File"]
    domain = ".bilibili.com"
    
    cookies = cookie_str.split(';')
    for cookie in cookies:
        cookie = cookie.strip()
        if '=' in cookie:
            key, value = cookie.split('=', 1)
            key = key.strip()
            value = value.strip()
            # Netscape 格式：domain flag path secure expiry name value
            lines.append(f"{domain}\tTRUE\t/\tFALSE\t0\t{key}\t{value}")
    
    return '\n'.join(lines)


def run_yt_dlp_api(url: str, cookie: Optional[str] = None, extra_args: List[str] = None) -> Optional[Any]:
    """执行 yt-dlp 命令（API 版本）"""
    import subprocess
    
    yt_dlp = get_yt_dlp_path()
    cmd = [yt_dlp, "--dump-json", "--no-download"]
    
    # 处理 Cookie（转换为 Netscape 格式）
    if cookie:
        temp_cookie = tempfile.NamedTemporaryFile(mode='w', suffix='.txt', delete=False)
        netscape_cookie = convert_cookie_to_netscape(cookie)
        temp_cookie.write(netscape_cookie)
        temp_cookie.close()
        cmd.extend(["--cookies", temp_cookie.name])
    
    if extra_args:
        cmd.extend(extra_args)
    
    cmd.append(url)
    
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        
        # 清理临时 Cookie 文件
        if cookie:
            try:
                os.unlink(temp_cookie.name)
            except:
                pass
        
        if result.returncode != 0:
            return {"error": result.stderr}
        
        return result.stdout
    except Exception as e:
        return {"error": str(e)}


@app.post("/api/uploader/info", response_model=UploaderInfoResponse)
async def get_uploader_info(request: UploaderInfoRequest):
    """
    获取 B 站 UP 主主页信息及视频详情
    
    **功能**:
    1. 获取 UP 主基本信息（名称、UID 等）
    2. 获取 UP 主视频列表（含封面图）
    3. 获取每个视频的详细信息（播放量、点赞数等）
    
    **适用于 Coze API 调用**
    """
    logger.info(f"Getting uploader info: {request.uploader_url}, max_videos: {request.max_videos}")
    
    # 1. 获取视频列表（不使用 flat-playlist，直接获取完整信息）
    output = run_yt_dlp_api(
        request.uploader_url,
        request.cookie,
        ["--playlist-end", str(request.max_videos)]
    )
    
    if not output or isinstance(output, dict) and "error" in output:
        return UploaderInfoResponse(
            success=False,
            error=output.get("error", "Unknown error") if isinstance(output, dict) else "Unknown error"
        )
    
    # 解析多行 JSON（每行一个视频）
    videos = []
    uploader_info = None
    logger.info(f"Raw output lines: {len(output.strip().split(chr(10))) if output else 0}")
    for line in output.strip().split('\n'):
        if line.strip():
            try:
                entry = json.loads(line)
                logger.info(f"Parsed entry: id={entry.get('id')}, title={entry.get('title', '')[:30] if entry.get('title') else 'EMPTY'}")
                
                # 跳过播放列表信息行（没有 id 字段）
                if not entry.get("id"):
                    logger.info("Skipping entry without id")
                    continue
                
                # 从第一个视频提取 UP 主信息
                if uploader_info is None:
                    uploader_info = {
                        "uploader": entry.get("uploader", ""),
                        "uploader_id": entry.get("uploader_id", ""),
                        "url": request.uploader_url,
                    }
                
                videos.append({
                    "index": len(videos) + 1,
                    "title": entry.get("title", ""),
                    "id": entry.get("id", ""),
                    "url": f"https://www.bilibili.com/video/{entry.get('id', '')}",
                    "thumbnail": entry.get("thumbnail", ""),
                    "duration_string": format_duration_string(entry.get("duration_string", ""), entry.get("duration")),
                })
            except json.JSONDecodeError as e:
                logger.error(f"JSON decode error: {e}")
                continue
    
    if not uploader_info:
        return UploaderInfoResponse(
            success=False,
            error="Failed to get uploader info"
        )
    
    result = {
        "uploader_info": uploader_info,
        "videos": videos,
        "video_count": len(videos),
    }
    
    # 2. 获取视频详情（如果需要）
    if request.get_details and videos:
        video_details = []
        for video in videos:
            output = run_yt_dlp_api(video["url"], request.cookie)
            
            if output and not isinstance(output, dict) or not (isinstance(output, dict) and output.get("error")):
                try:
                    if isinstance(output, dict):
                        continue
                    detail = json.loads(output.strip())
                    video_details.append({
                        "title": detail.get("title", ""),
                        "id": detail.get("id", ""),
                        "url": detail.get("webpage_url", ""),
                        "thumbnail": detail.get("thumbnail", ""),
                        "duration_string": format_duration_string(detail.get("duration_string", ""), detail.get("duration")),
                        "view_count": detail.get("view_count", 0),
                        "like_count": detail.get("like_count", 0),
                        "comment_count": detail.get("comment_count", 0),
                        "upload_date": detail.get("upload_date", ""),
                        "tags": detail.get("tags", []),
                        "description": detail.get("description", ""),
                    })
                except json.JSONDecodeError:
                    continue
        
        result["video_details"] = video_details
        result["details_count"] = len(video_details)
    
    return UploaderInfoResponse(
        success=True,
        data=result
    )


