@app.post("/api/coze/webhook")
async def coze_webhook(request: CozeWebhookRequest):
    """
    Coze Webhook 接口（支持抖音和哔哩哔哩）
    
    **请求示例**:
    ```json
    {
        "url": "https://www.bilibili.com/video/BV1xx411c7mD",
        "platform": "auto",
        "action": "info",
        "cookie": "your_cookie_string"
    }
    ```
    
    **支持的平台**:
    - bilibili: https://www.bilibili.com/video/BVxxx
    - douyin: https://www.douyin.com/video/xxx
    """
    logger.info(f"Coze webhook: {request.action} for {request.url}, platform: {request.platform}")
    
    if request.action == "info":
        info = extract_video_info(request.url, request.platform, request.cookie)
        
        if "error" in info:
            return JSONResponse({
                "success": False,
                "error": info["error"]
            })
        
        # 检测实际平台
        detected_platform = detect_platform(request.url)
        
        return JSONResponse({
            "success": True,
            "data": {
                "platform": detected_platform,
                "title": info.get("title", ""),
                "author": info.get("uploader", "") if detected_platform == "douyin" else info.get("uploader", ""),
                "duration": format_duration_string(info.get("duration_string", ""), info.get("duration")),
                "view_count": info.get("view_count", 0),
                "like_count": info.get("like_count", 0),
                "url": info.get("webpage_url", ""),
                "thumbnail": info.get("thumbnail", ""),
            }
        })
    
    elif request.action == "download":
        temp_dir = tempfile.mkdtemp(prefix="video_download_")
        
        result = download_video(
            request.url,
            temp_dir,
            request.quality,
            request.platform,
            request.cookie
        )
        
        if not result.get("success"):
            return JSONResponse({
                "success": False,
                "error": result.get("error", "Download failed")
            })
        
        return JSONResponse({
            "success": True,
            "data": {
                "filename": result.get("filename", ""),
                "file_path": result.get("file_path", ""),
                "message": "Video downloaded successfully"
            }
        })
    
    else:
        return JSONResponse({
            "success": False,
            "error": f"Unknown action: {request.action}"
        }, status_code=400)


